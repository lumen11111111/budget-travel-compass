import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

type ArticleSource = { title: string; url: string };

const researchRoot = path.join(process.cwd(), "content-preparation", "research");
const outputPath = path.join(process.cwd(), "src", "content", "article-sources.generated.ts");

function splitTableRow(line: string) {
  return line.trim().replace(/^\|/, "").replace(/\|$/, "").split("|").map((cell) => cell.trim());
}

function isSeparatorRow(cells: string[]) {
  return cells.length > 0 && cells.every((cell) => /^:?-{3,}:?$/.test(cell));
}

function cleanTitle(value: string) {
  return value
    .replace(/\[([^\]]+)]\([^)]+\)/g, "$1")
    .replace(/[*_`]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function cleanUrl(value: string) {
  const match = value.match(/https?:\/\/[^\s)>]+/i);
  return match?.[0].replace(/[.,;:!?]+$/, "") ?? null;
}

function parseLedger(markdown: string): ArticleSource[] {
  const lines = markdown.split(/\r?\n/);
  const sources = new Map<string, ArticleSource>();

  for (let index = 0; index < lines.length - 2; index += 1) {
    const headers = splitTableRow(lines[index]).map((header) => header.toLowerCase());
    const separator = splitTableRow(lines[index + 1]);
    if (!isSeparatorRow(separator)) continue;

    const sourceIndex = headers.findIndex((header) => header === "source" || header === "source name");
    const urlIndex = headers.findIndex((header) => header === "url");
    if (sourceIndex < 0 && urlIndex < 0) continue;

    for (let rowIndex = index + 2; rowIndex < lines.length; rowIndex += 1) {
      if (!lines[rowIndex].trim().startsWith("|")) break;
      const cells = splitTableRow(lines[rowIndex]);
      const sourceCell = sourceIndex >= 0 ? cells[sourceIndex] ?? "" : "";
      const urlCell = urlIndex >= 0 ? cells[urlIndex] ?? "" : "";
      const markdownLink = sourceCell.match(/\[([^\]]+)]\((https?:\/\/[^)\s]+)\)/i);
      const url = cleanUrl(urlCell) ?? (markdownLink ? cleanUrl(markdownLink[2]) : null);
      if (!url) continue;

      const title = cleanTitle(sourceCell) || new URL(url).hostname.replace(/^www\./, "");
      if (!sources.has(url)) sources.set(url, { title, url });
    }
  }

  return [...sources.values()];
}

function parseSlug(markdown: string, directory: string) {
  const slug = markdown.match(/^slug:\s*["']?([^"'\s]+)["']?\s*$/m)?.[1];
  if (!slug) throw new Error(`Missing slug in ${directory}/ARTICLE_DRAFT.md`);
  return slug;
}

function renderManifest(entries: Array<[string, ArticleSource[]]>) {
  const body = entries
    .map(([slug, sources]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(sources, null, 2).replace(/^/gm, "  ").trimStart()},`)
    .join("\n");

  return `// Generated by scripts/generate-article-sources.ts. Do not edit manually.\n\nexport interface ArticleSource {\n  title: string;\n  url: string;\n}\n\nexport const articleSourcesBySlug: Readonly<Record<string, readonly ArticleSource[]>> = {\n${body}\n};\n`;
}

async function main() {
  const directories = (await readdir(researchRoot, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory() && /^BTC-\d+$/.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  const entries: Array<[string, ArticleSource[]]> = [];

  for (const directory of directories) {
    const folder = path.join(researchRoot, directory);
    const [draft, ledger] = await Promise.all([
      readFile(path.join(folder, "ARTICLE_DRAFT.md"), "utf8"),
      readFile(path.join(folder, "CLAIM_SOURCE_LEDGER.md"), "utf8"),
    ]);
    entries.push([parseSlug(draft, directory), parseLedger(ledger)]);
  }

  entries.sort(([a], [b]) => a.localeCompare(b));
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, renderManifest(entries), "utf8");

  const sourced = entries.filter(([, sources]) => sources.length > 0).length;
  const totalSources = entries.reduce((sum, [, sources]) => sum + sources.length, 0);
  console.log(`Generated ${entries.length} guide entries: ${sourced} with web sources, ${totalSources} unique source links.`);
  const withoutSources = entries.filter(([, sources]) => sources.length === 0).map(([slug]) => slug);
  if (withoutSources.length) console.log(`No web sources in ledger: ${withoutSources.join(", ")}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
